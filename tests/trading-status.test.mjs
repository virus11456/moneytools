import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { tradingStatus, countdown } from '../app/tradingStatus.ts';
const calendars = JSON.parse(readFileSync(new URL('../app/calendars/trading-sessions.json', import.meta.url)));
const at = (market, instant) => tradingStatus(calendars[market], Date.parse(instant));
assert.equal(at('US', '2026-09-16T13:29:59Z').state, 'closed');
assert.equal(at('US', '2026-09-16T13:30:00Z').state, 'open');
assert.equal(at('US', '2026-09-16T20:00:00Z').state, 'closed');
assert.equal(at('US', '2026-01-05T14:29:59Z').state, 'closed');
assert.equal(at('US', '2026-01-05T14:30:00Z').state, 'open');
assert.equal(at('US', '2026-03-06T14:30:00Z').state, 'open');
assert.equal(at('US', '2026-03-09T13:30:00Z').state, 'open');
assert.equal(at('US', '2026-11-02T13:30:00Z').state, 'closed');
assert.equal(at('US', '2026-11-02T14:30:00Z').state, 'open');
assert.equal(at('US', '2026-11-26T15:00:00Z').nextOpenAt, Date.parse('2026-11-27T14:30:00Z'));
assert.equal(at('US', '2026-11-27T17:59:59Z').state, 'open');
assert.equal(at('US', '2026-11-27T18:00:00Z').state, 'closed');
assert.equal(at('US', '2026-12-24T18:00:00Z').nextOpenAt, Date.parse('2026-12-28T14:30:00Z'));
assert.equal(at('TW', '2026-09-17T00:59:59Z').state, 'closed');
assert.equal(at('TW', '2026-09-17T01:00:00Z').state, 'open');
assert.equal(at('TW', '2026-09-17T05:30:00Z').state, 'closed');
assert.equal(at('TW', '2026-09-25T02:00:00Z').nextOpenAt, Date.parse('2026-09-29T01:00:00Z'));
assert.equal(at('TW', '2026-02-12T02:00:00Z').nextOpenAt, Date.parse('2026-02-23T01:00:00Z'));
assert.equal(at('TW', '2026-10-26T02:00:00Z').nextOpenAt, Date.parse('2026-10-27T01:00:00Z'));
assert.equal(at('TW', '2026-09-19T02:00:00Z').nextOpenAt, Date.parse('2026-09-21T01:00:00Z'));
assert.equal(at('TW', '2027-01-04T02:00:00Z').state, 'unknown');
assert.equal(at('TW', '2026-12-31T06:00:00Z').state, 'unknown');
assert.equal(tradingStatus(null, Date.now()).state, 'unknown');
assert.equal(tradingStatus(calendars.US, NaN).state, 'unknown');
assert.equal(countdown(86400000 + 3661000), '1 天 01:01:01');
assert.equal(countdown(1), '00:00:01');
assert.equal(countdown(-1), '00:00:00');
console.log('Trading status passed: both exchanges, DST changes, holidays, Lunar New Year settlement days, early closes, exact boundaries and calendar expiry.');
